/**
 * LINE 機能をこのデプロイで顧客・施設に見せてよいかの単一の判定。
 *
 * 【背景・2026年7月29日】
 * LINE の送信コードは予約・キャンセル・ステータス変更・リマインドに配線済みで、
 * LINE_CHANNEL_ACCESS_TOKEN_CARELINK も設定済みだった。しかし顧客が連携する入口
 * （公式アカウントのリッチメニュー＝LIFF）が無いため、本番では
 * line_user_links 0件・line_notification_logs 0件＝一度も送信されていなかった。
 * それでも UI は「LINE連携すると予約確認が届きます」「LINEで送る（有料）」と
 * 表示し続けており、顧客は案内どおりに動けず、施設は押しても 403 になるボタンを
 * 見せられていた。神原さんの判断で【ローンチ段階では LINE を設定しない】と決定
 * （後日実装する可能性はある）。
 *
 * 【なぜ手動フラグにしないか＝真の予防】
 * `const LAUNCH_HIDDEN = true` のような定数で隠すと、後で LIFF を設定したときに
 * フラグを戻し忘れ、設定したのに UI が出ないという逆の事故が起きる。逆にフラグだけ
 * 戻して LIFF を入れ忘れれば、元の「動かないのに見せる」状態が再発する。
 * どちらも「表示」と「実際に使えるか」が別々に管理されることが原因なので、
 * 表示を設定そのものに従属させる。この関数が true を返すのは
 * NEXT_PUBLIC_LIFF_ID が入っているときだけで、神原さんが Vercel に値を入れた瞬間に
 * 顧客の連携導線も施設の LINE 項目も自動で復活する。コード変更は要らない。
 *
 * 【なぜ LIFF ID を基準にするか】
 * アクセストークンやチャネルシークレットが揃っていても、顧客が自分の LINE を
 * 結び付ける導線が無ければ送信先が存在せず、機能は成立しない。その導線の実体が
 * LIFF であるため、LIFF ID の有無が「LINE が使えるか」と一致する。
 */
export function isLineEnabled(): boolean {
  return !!process.env.NEXT_PUBLIC_LIFF_ID;
}
