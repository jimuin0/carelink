import { toIcalLocalDateTime } from '../ical-date';

test.each([
  ['2030-01-07', '10:30', '20300107T103000'],
  ['2030-01-07', '10:30:15', '20300107T103015'],
  ['2030-01-07', '00:00', '20300107T000000'],
  ['2030-01-07', '24:00', '20300108T000000'],
  ['2030-01-31', '24:00:00', '20300201T000000'],
  ['2030-12-31', '24:00', '20310101T000000'],
  ['2028-02-28', '24:00', '20280229T000000'],
  ['2028-02-29', '24:00', '20280301T000000'],
])('calendar date %s %s normalizes to %s', (date, time, expected) => {
  expect(toIcalLocalDateTime(date, time)).toBe(expected);
});
